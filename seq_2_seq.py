import pandas as pd
from typing import List

def encode(df: pd.DataFrame, mode: str = "single") -> pd.DataFrame:
    """
    Encodes dataset into prompt/target text pairs for Seq2Seq models.

    Args:
        df: Input DataFrame from load.load_and_merge_data().
        mode: 'single' for isolated word prompts, or 'group6' for 6-word paradigm prompts.

    Example Input (df row):
        lemma="გაკეთება", verb_class="1", screeve="imperfect",
        subject="1s", form="გავაკეთებდი", segmented_target="გა-ვ-ა-კეთ-ებ-დი"

    Example Output (Single mode DataFrame row):
        input_text:  "lemma: გაკეთება | class: 1 | screeve: imperfect | subject: 1s | surface: გავაკეთებდი"
        target_text: "გა-ვ-ა-კეთ-ებ-დი"

    Example Output (Group6 mode DataFrame row):
        input_text:  "lemma: გაკეთება | class: 1 | screeve: imperfect | paradigm: გავაკეთებდი | გააკეთებდი | გააკეთებს..."
        target_text: "გა-ვ-ა-კეთ-ებ-დი | გა-ა-კეთ-ებ-დი | გა-ა-კეთ-ებ-ს..."
    """
    if mode == "single":
        records = []
        for _, row in df.iterrows():
            prompt = (
                f"lemma: {row['lemma']} | class: {row['verb_class']} | "
                f"screeve: {row['screeve']} | subject: {row['subject']} | "
                f"surface: {row['form']}"
            )
            records.append({
                "input_text": prompt,
                "target_text": row["segmented_target"]
            })
        return pd.DataFrame(records)

    elif mode == "group6":
        records = []
        grouped = df.groupby(["word_id", "screeve"])
        for (w_id, screeve), group in grouped:
            prompt = (
                f"lemma: {group['lemma'].iloc[0]} | class: {group['verb_class'].iloc[0]} | "
                f"screeve: {screeve} | paradigm: {' | '.join(group['form'].tolist())}"
            )
            targets = " | ".join(group["segmented_target"].tolist())
            records.append({
                "input_text": prompt,
                "target_text": targets
            })
        return pd.DataFrame(records)
    else:
        raise ValueError("mode must be 'single' or 'group6'")


def decode(pred_str: str, mode: str = "single") -> List[str]:
    """
    Decodes generated string predictions into cleaned segmented strings.

    Args:
        pred_str: Raw text generated by the model.
        mode: 'single' or 'group6'.

    Example Input (Single):
        pred_str = "გა-ვ-ა-კეთ-ებ-დი"
    Example Output (Single):
        ["გა-ვ-ა-კეთ-ებ-დი"]

    Example Input (Group6):
        pred_str = "გა-ვ-ა-კეთ-ებ-დი | გა-ა-კეთ-ებ-დი | გა-ა-კეთ-ებ-ს"
    Example Output (Group6):
        ["გა-ვ-ა-კეთ-ებ-დი", "გა-ა-კეთ-ებ-დი", "გა-ა-კეთ-ებ-ს"]
    """
    if mode == "single":
        return [pred_str.strip()]
    elif mode == "group6":
        return [s.strip() for s in pred_str.split("|")]
    else:
        raise ValueError("mode must be 'single' or 'group6'")